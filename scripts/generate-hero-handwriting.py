"""Generate actual pen centre-lines. Python 3, no third-party packages.

Source and SIL OFL 1.1 attribution: assets/hero-handwriting/README.md.
"""
from pathlib import Path
import math
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "scripts/assets/hero-handwriting/EMSAllure.svg"
TARGET = ROOT / "src/assets/handwriting/hero-pen-paths.ts"
TEXT = "Tworzymy inteligentne przestrzenie"


def distance(a, b):
    return math.hypot(a[0] - b[0], a[1] - b[1])


def controls(points, i):
    """Round the digitized trace while retaining sharp pen reversals."""
    a, b = points[i], points[i + 1]
    before = points[max(0, i - 1)]
    after = points[min(len(points) - 1, i + 2)]

    def handle(origin, neighbor, previous, following, sign):
        incoming = (origin[0] - previous[0], origin[1] - previous[1])
        outgoing = (following[0] - origin[0], following[1] - origin[1])
        product = math.hypot(*incoming) * math.hypot(*outgoing)
        if product and sum(x * y for x, y in zip(incoming, outgoing)) / product < -0.2:
            return origin
        tangent = ((following[0] - previous[0]) / 6, (following[1] - previous[1]) / 6)
        length = math.hypot(*tangent)
        limit = distance(origin, neighbor) * 0.35
        ratio = min(1, limit / length) if length else 0
        return (origin[0] + sign * tangent[0] * ratio, origin[1] + sign * tangent[1] * ratio)

    return handle(a, b, before, b, 1), handle(b, a, a, after, -1)


def curve_point(a, c1, c2, b, t):
    u = 1 - t
    return tuple(u**3*a[k] + 3*u*u*t*c1[k] + 3*u*t*t*c2[k] + t**3*b[k] for k in (0, 1))


def main():
    font = ET.parse(SOURCE).getroot().find(".//{http://www.w3.org/2000/svg}font")
    glyphs = {g.get("unicode"): g for g in font if g.tag.endswith("glyph")}
    strokes, x = [], 0
    for letter in TEXT:
        glyph = glyphs[letter]
        d = glyph.get("d", "")
        assert set(re.findall(r"[A-Za-z]", d)) <= {"M", "L"}, "Unexpected font path format"
        # Each M is a separate pen movement, including dots and crossbars.
        for subpath in re.findall(r"M[^M]+", d):
            values = list(map(float, re.findall(r"-?\d+(?:\.\d+)?", subpath)))
            strokes.append([(x + values[i], -values[i+1]) for i in range(0, len(values), 2)])
        x += float(glyph.get("horiz-adv-x", font.get("horiz-adv-x")))

    all_points = [p for points in strokes for p in points]
    left = min(p[0] for p in all_points) - 45
    top = min(p[1] for p in all_points) - 45
    width = max(p[0] for p in all_points) - left + 45
    height = max(p[1] for p in all_points) - top + 45
    scale = 1400 / width
    paths = []
    for points in strokes:
        points = [((p[0]-left)*scale, (p[1]-top)*scale) for p in points]
        commands = [f"M{points[0][0]:.2f},{points[0][1]:.2f}"]
        length = 0
        for i in range(len(points)-1):
            a, b = points[i], points[i+1]
            c1, c2 = controls(points, i)
            commands.append(f"C{c1[0]:.2f},{c1[1]:.2f} {c2[0]:.2f},{c2[1]:.2f} {b[0]:.2f},{b[1]:.2f}")
            last = a
            for step in range(1, 25):
                point = curve_point(a, c1, c2, b, step/24)
                length += distance(last, point)
                last = point
        paths.append((" ".join(commands), length))

    total, cursor = sum(length for _, length in paths), 0
    lines = [
        "// Generated by scripts/generate-hero-handwriting.py; do not edit geometry by hand.",
        "// EMS Allure / Allura pen paths, SIL OFL 1.1. See hero-pen-OFL.txt and scripts/assets/hero-handwriting/README.md.",
        f"export const HERO_PEN_VIEWBOX = '0 0 1400 {height*scale:.2f}';",
        "export const HERO_PEN_STROKES = [",
    ]
    for d, length in paths:
        lines.append(f"  {{ at: {cursor/total:.8f}, duration: {length/total:.8f}, d: '{d}' }},")
        cursor += length
    lines.append("] as const;\n")
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {len(paths)} pen strokes, 1400 x {height*scale:.2f}, {TARGET.stat().st_size} bytes")


if __name__ == "__main__":
    main()
